"""Create one exploratory signal and feature plot for every recording CSV.

Plots use relative time within each file. They do not assign fatigue phases or
assume that a file is a complete set or a single contraction.
"""

from __future__ import annotations

import argparse
import html
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


def make_record_plot(
    root: Path,
    row: pd.Series,
    windows: pd.DataFrame,
    output_path: Path,
) -> None:
    raw_path = root / str(row["source_file"])
    raw = pd.read_csv(raw_path, usecols=["Relative_Time_s", "Voltage_mV"])
    time = pd.to_numeric(raw["Relative_Time_s"], errors="raise").to_numpy(dtype=float)
    signal = pd.to_numeric(raw["Voltage_mV"], errors="raise").to_numpy(dtype=float)
    if len(time) != len(signal) or len(time) == 0:
        raise ValueError(f"Invalid signal arrays in {raw_path}")

    # Insert NaNs across recorded timestamp gaps so the line does not imply
    # samples were acquired during a discontinuity.
    interval = np.diff(time)
    dt = float(np.median(interval)) if len(interval) else np.nan
    breaks = np.flatnonzero(interval > dt * 1.01) + 1 if np.isfinite(dt) else []
    plot_time = time.copy()
    plot_signal = signal.copy()
    plot_time[breaks] = np.nan
    plot_signal[breaks] = np.nan

    fig, axes = plt.subplots(3, 1, figsize=(12, 8.2), sharex=True, constrained_layout=True)
    axes[0].plot(plot_time, plot_signal, color="#285f78", linewidth=0.45, rasterized=True)
    axes[0].set_ylabel("Voltage_mV column\n(unverified units)")
    axes[0].set_title(
        f"{row['subject_id']} | {row['repetition_id']} | {row['side']} | "
        f"{time[-1] - time[0]:.1f} s recording"
    )
    axes[0].grid(alpha=0.2)

    ordered = windows.sort_values("start_time_s")
    feature_time = (ordered["start_time_s"].to_numpy(float) + ordered["end_time_s"].to_numpy(float)) / 2
    rms = ordered["rms"].to_numpy(float)
    axes[1].plot(feature_time, rms, color="#a94a32", linewidth=0.8)
    axes[1].set_ylabel("RMS\n(recorded units)")
    axes[1].grid(alpha=0.2)

    mdf = ordered["mdf_hz_filtered"].to_numpy(float)
    mnf = ordered["mnf_hz_filtered"].to_numpy(float)
    axes[2].plot(feature_time, mdf, color="#31688e", linewidth=0.8, label="MDF")
    axes[2].plot(feature_time, mnf, color="#d08c28", linewidth=0.8, label="MNF")
    axes[2].set_ylabel("Frequency (Hz)\n(unfiltered, exploratory)")
    axes[2].set_xlabel("Time within this file (s)")
    axes[2].legend(frameon=False, ncol=2, loc="upper right")
    axes[2].grid(alpha=0.2)
    fig.suptitle("Exploratory view — not fatigue labels", fontsize=10, color="#555555")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=130)
    plt.close(fig)


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--dataset", type=Path,
        default=root / "data" / "features_dataset_corrected_unlabeled.csv",
        help="Corrected feature CSV generated by src/features.py",
    )
    parser.add_argument(
        "--output-dir", type=Path,
        default=root / "results" / "recording_plots",
        help="Folder for per-recording PNGs and the HTML gallery",
    )
    args = parser.parse_args()

    frame = pd.read_csv(args.dataset)
    required = {
        "subject_id", "record_id", "source_file", "repetition_id", "side",
        "start_time_s", "end_time_s", "rms", "mdf_hz_filtered", "mnf_hz_filtered",
    }
    missing = required.difference(frame.columns)
    if missing:
        raise ValueError(f"Feature dataset is missing columns: {sorted(missing)}")

    gallery_items: list[tuple[str, str, str]] = []
    for _, record in frame[["subject_id", "record_id", "source_file", "repetition_id", "side"]].drop_duplicates().iterrows():
        group = frame[frame["record_id"] == record["record_id"]]
        subject = str(record["subject_id"])
        repetition = str(record["repetition_id"])
        side = str(record["side"])
        relative_plot = Path(subject) / f"{repetition}_{side}.png"
        output_path = args.output_dir / relative_plot
        make_record_plot(root, record, group, output_path)
        caption = f"{subject} — {repetition} — {side}"
        gallery_items.append((subject, caption, relative_plot.as_posix()))

    html_path = args.output_dir / "index.html"
    sections = []
    for subject in sorted({item[0] for item in gallery_items}):
        cards = []
        for _, caption, image_path in sorted(item for item in gallery_items if item[0] == subject):
            escaped_caption = html.escape(caption)
            escaped_path = html.escape(image_path, quote=True)
            cards.append(
                f'<article><h3>{escaped_caption}</h3>'
                f'<a href="{escaped_path}"><img loading="lazy" src="{escaped_path}" '
                f'alt="{escaped_caption}" style="width:min(100%,1000px)"></a></article>'
            )
        sections.append(f"<section><h2>{html.escape(subject)}</h2>{''.join(cards)}</section>")

    document = """<!doctype html>
<html lang="es"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width">
<title>Gráficas exploratorias por registro</title>
<style>body{font:16px system-ui,sans-serif;max-width:1100px;margin:2rem auto;padding:0 1rem;color:#222}
section{border-top:1px solid #bbb;margin-top:2rem}article{margin:1.5rem 0 2.5rem}img{height:auto;border:1px solid #ddd}
.note{background:#fff7df;padding:1rem}</style></head><body>
<h1>Señal y características por archivo</h1>
<p class="note">Cada gráfica muestra el tiempo relativo dentro de un CSV. MDF/MNF son valores exploratorios sin filtrado.
Las curvas no asignan fases ni confirman fatiga; los códigos R y los límites de cada archivo no están validados como series experimentales completas.</p>
""" + "\n".join(sections) + "\n</body></html>"
    html_path.parent.mkdir(parents=True, exist_ok=True)
    html_path.write_text(document, encoding="utf-8")
    print(f"Recordings plotted: {len(gallery_items)}")
    print(f"Gallery: {html_path}")


if __name__ == "__main__":
    main()
