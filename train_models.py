"""Train exploratory models for within-recording temporal progression.

IMPORTANT: labels are early/middle/late thirds of each CSV recording. They are
not observed or validated physiological fatigue labels. Each CSV is treated as
one recording solely to make a first reproducible prototype possible.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.discriminant_analysis import LinearDiscriminantAnalysis
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import balanced_accuracy_score, classification_report, confusion_matrix, f1_score
from sklearn.model_selection import LeaveOneGroupOut, cross_val_predict
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler


FEATURES = ["rms", "mav", "variance", "waveform_length"]
CLASSES = ["early", "middle", "late"]


def load_and_label(path: Path) -> pd.DataFrame:
    frame = pd.read_csv(path)
    required = {"subject_id", "record_id", *FEATURES}
    missing = required.difference(frame.columns)
    if missing:
        raise ValueError(f"Dataset is missing required columns: {sorted(missing)}")
    frame = frame.dropna(subset=["subject_id", "record_id", *FEATURES]).copy()
    if frame.empty:
        raise ValueError("No complete feature rows remain after removing missing values")

    # Provisional proxy target: relative window order within each CSV file.
    # MDF/MNF and absolute time are deliberately not model inputs.
    rank = frame.groupby("record_id", sort=False).cumcount()
    count = frame.groupby("record_id", sort=False)["record_id"].transform("size")
    relative_position = (rank + 0.5) / count
    frame["stage_proxy"] = pd.cut(
        relative_position,
        bins=[0.0, 1 / 3, 2 / 3, 1.0000001],
        labels=CLASSES,
        include_lowest=True,
        right=True,
    ).astype(str)
    if frame["stage_proxy"].isna().any() or (frame["stage_proxy"] == "nan").any():
        raise ValueError("Could not assign a temporal stage to every window")
    return frame


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--dataset", type=Path,
        default=root / "data" / "features_dataset_corrected_unlabeled.csv",
        help="Corrected feature CSV generated by src/features.py",
    )
    parser.add_argument("--output-dir", type=Path, default=root / "results")
    args = parser.parse_args()

    data = load_and_label(args.dataset)
    if data["subject_id"].nunique() < 3:
        raise ValueError("At least three participants are required for subject-wise validation")

    X = data[FEATURES].to_numpy(dtype=float)
    y = data["stage_proxy"].to_numpy()
    groups = data["subject_id"].astype(str).to_numpy()
    cv = LeaveOneGroupOut()
    models = {
        "LDA": make_pipeline(StandardScaler(), LinearDiscriminantAnalysis()),
        "RandomForest": RandomForestClassifier(
            n_estimators=300,
            max_depth=8,
            min_samples_leaf=20,
            class_weight="balanced",
            random_state=42,
            n_jobs=-1,
        ),
    }

    args.output_dir.mkdir(parents=True, exist_ok=True)
    prediction_frames = []
    metric_lines = [
        "EXPLORATORY TEMPORAL-STAGE MODEL RESULTS",
        "Target: early/middle/late thirds within each CSV recording.",
        "This is a time-progression proxy, NOT validated physiological fatigue.",
        "Features: RMS, MAV, variance, waveform length; MDF/MNF/time excluded.",
        "Validation: Leave-One-Subject-Out (all windows from each test subject held out).",
        f"Participants: {data['subject_id'].nunique()}; recordings: {data['record_id'].nunique()}; windows: {len(data)}",
        "",
        "Proxy class counts:",
        data["stage_proxy"].value_counts().reindex(CLASSES, fill_value=0).to_string(),
        "",
    ]
    for name, model in models.items():
        predicted = cross_val_predict(model, X, y, groups=groups, cv=cv, method="predict", n_jobs=1)
        metric_lines.extend([
            f"{name}",
            f"  Balanced accuracy: {balanced_accuracy_score(y, predicted):.4f}",
            f"  Macro F1: {f1_score(y, predicted, labels=CLASSES, average='macro', zero_division=0):.4f}",
            "  Classification report:",
            classification_report(y, predicted, labels=CLASSES, zero_division=0),
            "  Confusion matrix (true rows, predicted columns; early, middle, late):",
            str(confusion_matrix(y, predicted, labels=CLASSES)),
            "",
        ])
        part = data[["subject_id", "record_id", "repetition_id", "side", "window_index_in_record"]].copy()
        part["model"] = name
        part["true_stage_proxy"] = y
        part["predicted_stage_proxy"] = predicted
        prediction_frames.append(part)

    pred_path = args.output_dir / "temporal_stage_oof_predictions.csv"
    metrics_path = args.output_dir / "temporal_stage_model_metrics.txt"
    pd.concat(prediction_frames, ignore_index=True).to_csv(pred_path, index=False)
    metrics_path.write_text("\n".join(metric_lines), encoding="utf-8")
    print("IMPORTANT: these models predict within-file temporal stage, not confirmed fatigue.")
    print(f"Metrics: {metrics_path}")
    print(f"Out-of-fold predictions: {pred_path}")
    print("\n".join(line for line in metric_lines if "Balanced accuracy:" in line or "Macro F1:" in line))


if __name__ == "__main__":
    main()
