"""Average windowed RMS amplitude over time by R-code and side.

The signed raw waveforms are not averaged because the files do not share a
phase reference. RMS is used as an amplitude envelope. R1-R5 are treated as
filename codes; their experimental meaning is not independently confirmed.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


R_ORDER = ["R1", "R2", "R3", "R4", "R5"]
SIDE_COLORS = {"right": "#31688e", "left": "#d17a22"}


def mean_sd(frame: pd.DataFrame, group_columns: list[str], value: str, name: str) -> pd.DataFrame:
    grouped = frame.groupby(group_columns, observed=True)[value]
    result = grouped.agg(mean="mean", sd="std", n="count").reset_index()
    return result.rename(columns={"mean": f"mean_{name}", "sd": f"sd_{name}", "n": "participant_count"})


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--dataset", type=Path,
        default=root / "data" / "features_dataset_corrected_unlabeled.csv",
        help="Corrected feature CSV generated by src/features.py",
    )
    parser.add_argument(
        "--output-dir", type=Path,
        default=root / "results" / "repetition_averages",
        help="Folder for summary tables and mean curves",
    )
    args = parser.parse_args()

    frame = pd.read_csv(args.dataset)
    required = {
        "subject_id", "record_id", "source_file", "repetition_id", "side",
        "start_time_s", "end_time_s", "rms",
    }
    missing = required.difference(frame.columns)
    if missing:
        raise ValueError(f"Feature dataset is missing columns: {sorted(missing)}")
    frame = frame[frame["repetition_id"].isin(R_ORDER)].copy()
    if frame.empty:
        raise ValueError("No R1-R5 records found in the corrected feature dataset")

    # One-second bins smooth the overlapping 250 ms windows (125 ms step).
    frame["time_mid_s"] = (frame["start_time_s"] + frame["end_time_s"]) / 2
    frame["time_bin_s"] = np.floor(frame["time_mid_s"]).astype(int)

    # Average windows within a recording first, so files with more windows do
    # not receive more weight than other participants' recordings.
    record_time = (
        frame.groupby(
            ["subject_id", "record_id", "repetition_id", "side", "time_bin_s"],
            observed=True,
            as_index=False,
        )["rms"].mean()
    )
    record_summary = (
        frame.groupby(
            ["subject_id", "record_id", "repetition_id", "side", "source_file"],
            observed=True,
            as_index=False,
        ).agg(mean_rms_record=("rms", "mean"))
    )
    durations = []
    for source_file, group in record_summary.groupby("source_file", sort=True):
        raw_path = root / str(source_file)
        raw_time = pd.read_csv(raw_path, usecols=["Relative_Time_s"])["Relative_Time_s"].to_numpy(float)
        durations.append({"source_file": source_file, "recording_duration_s": float(raw_time[-1] - raw_time[0])})
    record_summary = record_summary.merge(pd.DataFrame(durations), on="source_file", validate="one_to_one")

    # If a participant has multiple files under one R/side code, combine them
    # first so the participant remains the unit of averaging.
    participant_time = (
        record_time.groupby(
            ["subject_id", "repetition_id", "side", "time_bin_s"], observed=True, as_index=False
        )["rms"].mean()
    )
    by_r = mean_sd(participant_time, ["repetition_id", "side", "time_bin_s"], "rms", "rms")
    by_r.rename(columns={"mean_rms": "mean_rms", "sd_rms": "sd_rms"}, inplace=True)

    # Overall mean across R1-R5: first average the available repetitions per
    # participant/side/time, then give each participant equal weight.
    participant_all_r = (
        participant_time.groupby(["subject_id", "side", "time_bin_s"], observed=True, as_index=False)["rms"]
        .mean()
    )
    all_r = mean_sd(participant_all_r, ["side", "time_bin_s"], "rms", "rms")

    # Summary of mean amplitude and duration per participant/side/R.
    participant_summary = (
        record_summary.groupby(["subject_id", "repetition_id", "side"], observed=True, as_index=False)
        .agg(mean_rms=("mean_rms_record", "mean"), mean_duration_s=("recording_duration_s", "mean"))
    )
    r_summary = []
    for (rep, side), group in participant_summary.groupby(["repetition_id", "side"], observed=True):
        r_summary.append({
            "repetition_id": rep,
            "side": side,
            "participant_count": group["subject_id"].nunique(),
            "mean_recording_duration_s": group["mean_duration_s"].mean(),
            "sd_recording_duration_s": group["mean_duration_s"].std(),
            "mean_rms_over_recording": group["mean_rms"].mean(),
            "sd_rms_over_recording": group["mean_rms"].std(),
        })
    r_summary = pd.DataFrame(r_summary)

    args.output_dir.mkdir(parents=True, exist_ok=True)
    by_r.to_csv(args.output_dir / "mean_rms_by_R_and_time.csv", index=False)
    all_r.to_csv(args.output_dir / "mean_rms_across_R_and_time.csv", index=False)
    r_summary.to_csv(args.output_dir / "mean_duration_and_amplitude_by_R.csv", index=False)

    fig, axes = plt.subplots(len(R_ORDER), 1, figsize=(11, 15), sharex=True, constrained_layout=True)
    for ax, rep in zip(axes, R_ORDER):
        subset = by_r[by_r["repetition_id"] == rep]
        for side, color in SIDE_COLORS.items():
            series = subset[subset["side"] == side].sort_values("time_bin_s")
            if series.empty:
                continue
            x = series["time_bin_s"].to_numpy(float) + 0.5
            y = series["mean_rms"].to_numpy(float)
            sd = series["sd_rms"].fillna(0).to_numpy(float)
            ax.plot(x, y, color=color, linewidth=1.6, label=f"{side} (n máximo={series['participant_count'].max()})")
            ax.fill_between(x, np.maximum(y - sd, 0), y + sd, color=color, alpha=0.16, linewidth=0)
        ax.set_title(rep)
        ax.set_ylabel("Mean RMS\n(recorded units)")
        ax.grid(alpha=0.2)
        ax.legend(frameon=False, ncol=2, fontsize=8, loc="upper right")
    axes[-1].set_xlabel("Mean relative time within each file (s; 1 s bins)")
    fig.suptitle("Mean amplitude envelope by filename R-code — mean ± SD across participants\nR codes are not confirmed experimental repetitions", fontsize=12)
    fig.savefig(args.output_dir / "mean_rms_by_R_over_time.png", dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(10, 5), constrained_layout=True)
    for side, color in SIDE_COLORS.items():
        series = all_r[all_r["side"] == side].sort_values("time_bin_s")
        if series.empty:
            continue
        x = series["time_bin_s"].to_numpy(float) + 0.5
        y = series["mean_rms"].to_numpy(float)
        sd = series["sd_rms"].fillna(0).to_numpy(float)
        ax.plot(x, y, color=color, linewidth=1.8, label=side)
        ax.fill_between(x, np.maximum(y - sd, 0), y + sd, color=color, alpha=0.17, linewidth=0)
    ax.set_title("Mean RMS amplitude across available R1-R5 files\nParticipant means are equally weighted")
    ax.set_xlabel("Mean relative time within each file (s; 1 s bins)")
    ax.set_ylabel("Mean RMS (recorded units)")
    ax.grid(alpha=0.2)
    ax.legend(frameon=False)
    fig.savefig(args.output_dir / "mean_rms_across_R_over_time.png", dpi=150)
    plt.close(fig)

    print(f"R codes averaged: {', '.join(R_ORDER)}")
    print(f"Output folder: {args.output_dir}")
    print(f"Per-R curves: {args.output_dir / 'mean_rms_by_R_over_time.png'}")
    print(f"Across-R mean: {args.output_dir / 'mean_rms_across_R_over_time.png'}")
    print(f"Duration/amplitude table: {args.output_dir / 'mean_duration_and_amplitude_by_R.csv'}")


if __name__ == "__main__":
    main()
